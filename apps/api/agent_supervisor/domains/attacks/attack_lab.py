CONTROL_DECISIONS = {"拒绝", "询问", "隔离"}


def _normalize_custom_attack_request(request: dict[str, Any]) -> dict[str, Any]:
    tool = str(request.get("tool") or "").strip().lower()
    if not tool:
        raise ValueError("tool 不能为空")
    raw_arguments = request.get("arguments")
    arguments = dict(raw_arguments) if isinstance(raw_arguments, dict) else {}
    command = str(request.get("command") or "").strip()
    if command:
        if tool != "code.run":
            raise ValueError("command 仅适用于 code.run 工具")
        # The dedicated command field is the explicit UI/API input. It must be
        # authoritative when both JSON arguments and the field are supplied;
        # silently choosing one would make the executed call ambiguous.
        arguments["command"] = command
    execution_mode = str(request.get("execution_mode") or "sandbox")
    if execution_mode not in {"sandbox", "external_receipt"}:
        raise ValueError("execution_mode 必须是 sandbox 或 external_receipt")
    context_sources = request.get("context_sources")
    if not isinstance(context_sources, list):
        context_sources = ["user-payload"]
    result = {
        "payload": str(request.get("payload") or "")[:20000],
        "tool": tool,
        "arguments": arguments,
        "command": command,
        "agent_id": str(request.get("agent_id") or "custom-attack-agent")[:160],
        "agent_role": str(request.get("agent_role") or "attacker")[:160],
        "context_sources": [str(item)[:120] for item in context_sources[:20]],
        "execution_mode": execution_mode,
    }
    return result


def run_custom_attack_compare(request: dict[str, Any]) -> dict[str, Any]:
    """Run a caller-authored tool call in equal unguarded/guarded fixtures.

    The endpoint deliberately accepts a tool name and arguments generated by an
    external Agent. Execution still goes through the existing normalized tool
    contract and local SandboxPaths, so arbitrary host commands or network calls
    never reach the host.
    """
    normalized = _normalize_custom_attack_request(request)
    tool = normalized["tool"]
    arguments = normalized["arguments"]
    command = normalized["command"]
    payload = normalized["payload"]
    agent_id = normalized["agent_id"]
    agent_role = normalized["agent_role"]
    execution_mode = normalized["execution_mode"]
    execute_in_sandbox = execution_mode == "sandbox"
    context_sources = normalized["context_sources"]
    comparison_id = str(uuid4())
    base_conversation = f"custom-attack-{comparison_id}"
    tool_call = {"tool": tool, "arguments": arguments}
    comparison_tool_call = deepcopy(tool_call)
    baseline_sandbox = _comparison_sandbox(comparison_id, "without-guard")
    guarded_sandbox = _comparison_sandbox(comparison_id, "with-guard")
    init_sandbox(baseline_sandbox)
    init_sandbox(guarded_sandbox)
    baseline_before = _environment_snapshot(baseline_sandbox)
    guarded_before = _environment_snapshot(guarded_sandbox)
    base_event = {
        "conversation_id": base_conversation,
        "agent_id": agent_id,
        "agent_role": agent_role,
        "source_app": "智安哨自定义攻击入口",
        "model_input": payload,
        "model_output": payload,
        "context_sources": context_sources,
        "tool_call": tool_call,
        "execute_in_sandbox": execute_in_sandbox,
    }
    without = evaluate_agent_event(
        {**base_event, "conversation_id": f"{base_conversation}-without-guard"},
        guard_enabled=False,
        execute_in_sandbox=execute_in_sandbox,
        review_scope="experiment" if execute_in_sandbox else "operational",
        sandbox=baseline_sandbox,
    )
    baseline_after = _environment_snapshot(baseline_sandbox)
    guarded = evaluate_agent_event(
        {**base_event, "conversation_id": f"{base_conversation}-with-guard"},
        guard_enabled=True,
        execute_in_sandbox=execute_in_sandbox,
        review_scope="experiment" if execute_in_sandbox else "operational",
        sandbox=guarded_sandbox,
    )
    guarded_after = _environment_snapshot(guarded_sandbox)
    receipts: dict[str, dict[str, Any] | None] = (
        {
            "without_guard": _record_server_execution_receipt(without, comparison_tool_call, agent_id),
            "with_guard": _record_server_execution_receipt(guarded, comparison_tool_call, agent_id),
        }
        if execute_in_sandbox
        else {"without_guard": None, "with_guard": None}
    )
    comparison = _environment_comparison(
        comparison_id,
        comparison_tool_call,
        baseline_before,
        baseline_after,
        guarded_before,
        guarded_after,
        without,
        guarded,
    )
    result = {
        "comparison_id": comparison_id,
        "request": {
            "payload": payload,
            "tool": tool,
            "arguments": arguments,
            "command": command,
            "agent_id": agent_id,
            "agent_role": agent_role,
            "context_sources": base_event["context_sources"],
            "execution_mode": execution_mode,
        },
        "tool_call": comparison_tool_call,
        "without_guard": without,
        "with_guard": guarded,
        "environment_comparison": comparison,
        "summary": {
            "exposed_without_guard": bool(without.get("attack_success")),
            "controlled_with_guard": guarded.get("decision") in CONTROL_DECISIONS and not guarded.get("attack_success"),
            "decision_change": f"{without.get('decision', '')} -> {guarded.get('decision', '')}",
            "policy_id": guarded.get("policy_id", ""),
            "execution_status": (
                (receipts.get("with_guard") or {}).get("status")
                if receipts.get("with_guard")
                else guarded.get("execution_status", "")
            ),
            "receipt_required": bool(guarded.get("execution_receipt_required")),
            "receipts_complete": all(receipts.values()),
            "same_initial_state": comparison["integrity"]["same_initial_state"],
            "tool_call_hash": comparison["integrity"]["tool_call_hash"],
        },
        "audit": {
            "without_guard": {"audit_id": without.get("audit_id", ""), "audit_hash": (without.get("audit_log") or {}).get("audit_hash", "")},
            "with_guard": {"audit_id": guarded.get("audit_id", ""), "audit_hash": (guarded.get("audit_log") or {}).get("audit_hash", "")},
        },
        "receipts": receipts,
    }
    comparison_evidence = {
        "schema_version": "agent-supervisor.custom-comparison.v1",
        "comparison_id": comparison_id,
        "payload_hash": _stable_hash(payload),
        "tool_call_hash": tool_call_hash(comparison_tool_call),
        "agent_id": agent_id,
        "agent_role": agent_role,
        "context_sources": context_sources,
        "without_guard_audit_id": without.get("audit_id", ""),
        "with_guard_audit_id": guarded.get("audit_id", ""),
        "without_guard_audit_hash": (without.get("audit_log") or {}).get("audit_hash", ""),
        "with_guard_audit_hash": (guarded.get("audit_log") or {}).get("audit_hash", ""),
    }
    comparison_evidence["evidence_hash"] = _stable_hash(comparison_evidence)
    journal_event = append_runtime_event("custom-attack-comparison", comparison_evidence)
    result["provenance"] = {**comparison_evidence, "journal_event_id": journal_event["event_id"]}
    return result


def verify_custom_attack_chain_source(
    source_comparison_id: str,
    *,
    payload: str,
    tool_call: dict[str, Any],
    agent_id: str,
    agent_role: str,
    context_sources: list[str],
) -> dict[str, Any]:
    """Bind a chain to the two persisted audits produced by one comparison."""
    source_id = str(source_comparison_id or "").strip()
    if not source_id:
        raise ValueError("source_comparison_id 不能为空")
    event = load_runtime_event_by_payload_id("custom-attack-comparison", "comparison_id", source_id)
    if event is None:
        raise ValueError("来源对照不存在或已失效，请先运行当前 Payload 的攻防对照")
    evidence = event["payload"]
    stored_hash = str(evidence.get("evidence_hash", ""))
    unsigned = {key: value for key, value in evidence.items() if key != "evidence_hash"}
    if not stored_hash or stored_hash != _stable_hash(unsigned):
        raise ValueError("来源对照证据完整性校验失败")
    expected_tool_hash = tool_call_hash(tool_call)
    if (
        expected_tool_hash != str(evidence.get("tool_call_hash", ""))
        or _stable_hash(payload) != str(evidence.get("payload_hash", ""))
        or agent_id != str(evidence.get("agent_id", ""))
        or agent_role != str(evidence.get("agent_role", ""))
        or context_sources != list(evidence.get("context_sources") or [])
    ):
        raise ValueError("当前 Payload、Agent 或工具调用与来源对照不一致")
    audit_ids = [str(evidence.get("without_guard_audit_id", "")), str(evidence.get("with_guard_audit_id", ""))]
    audit_logs = [load_audit_log(audit_id) for audit_id in audit_ids]
    if any(log is None for log in audit_logs):
        raise ValueError("来源对照审计记录不完整")
    audit_hashes = [str(log.get("audit_hash", "")) for log in audit_logs if log]
    expected_audit_hashes = [
        str(evidence.get("without_guard_audit_hash", "")),
        str(evidence.get("with_guard_audit_hash", "")),
    ]
    if audit_hashes != expected_audit_hashes:
        raise ValueError("来源对照审计 Hash 与持久化记录不一致")
    return {
        "comparison_id": source_id,
        "trust": "verified",
        "tool_call_hash": expected_tool_hash,
        "audit_ids": sorted(audit_ids),
        "audit_hashes": sorted(audit_hashes),
        "evidence_hash": stored_hash,
    }


def run_custom_attack_once(request: dict[str, Any], *, guard_enabled: bool = True) -> dict[str, Any]:
    """Execute one caller-authored tool call as a runtime-supervision entry stage."""
    normalized = _normalize_custom_attack_request({**request, "execution_mode": "sandbox"})
    execution_id = str(uuid4())
    tool_call = {"tool": normalized["tool"], "arguments": deepcopy(normalized["arguments"])}
    sandbox = _comparison_sandbox(execution_id, "with-guard" if guard_enabled else "without-guard")
    init_sandbox(sandbox)
    before = _environment_snapshot(sandbox)
    evaluation = evaluate_agent_event(
        {
            "conversation_id": f"attack-chain-custom-{execution_id}",
            "agent_id": normalized["agent_id"],
            "agent_role": normalized["agent_role"],
            "source_app": "智安哨多 Agent 攻击链入口",
            "model_input": normalized["payload"],
            "model_output": normalized["payload"],
            "context_sources": normalized["context_sources"],
            "tool_call": tool_call,
            "execute_in_sandbox": True,
        },
        guard_enabled=guard_enabled,
        execute_in_sandbox=True,
        review_scope="experiment",
        sandbox=sandbox,
    )
    after = _environment_snapshot(sandbox)
    receipt = _record_server_execution_receipt(evaluation, tool_call, normalized["agent_id"])
    branch = _environment_branch(before, after, evaluation)
    return {
        "execution_id": execution_id,
        "request": normalized,
        "tool_call": tool_call,
        "guard_enabled": guard_enabled,
        "evaluation": evaluation,
        "environment": branch,
        "audit": {
            "audit_id": evaluation.get("audit_id", ""),
            "audit_hash": (evaluation.get("audit_log") or {}).get("audit_hash", ""),
        },
        "receipt": receipt,
        "summary": {
            "attack_success": bool(evaluation.get("attack_success")),
            "controlled": evaluation.get("decision") in CONTROL_DECISIONS and not evaluation.get("attack_success"),
            "decision": evaluation.get("decision", ""),
            "policy_id": evaluation.get("policy_id", ""),
            "execution_status": receipt.get("status", ""),
        },
    }


CUSTOM_CHAIN_STAGES: tuple[tuple[str, str, str, bool], ...] = (
    ("planner", "规划 Agent", "planner", False),
    ("executor", "执行 Agent", "executor", True),
    ("behavior-supervisor", "行为监督器", "behavior-supervisor", False),
    ("evaluator", "评测 Agent", "evaluator", False),
)


def run_custom_attack_chain(request: dict[str, Any], *, guard_enabled: bool = True) -> dict[str, Any]:
    """Run one caller-authored call through ordered runtime supervision roles.

    Every stage submits the *same* payload and tool call to the runtime
    supervisor with a shared conversation id.  Only the executor stage is
    allowed to perform the tool action; the other stages still produce a
    persisted supervisor evaluation, immutable audit hash and signed receipt
    recording that they did not execute.  This makes the chain evidence
    verifiable without multiplying the side effect four times.
    """
    normalized = _normalize_custom_attack_request({**request, "execution_mode": "sandbox"})
    execution_id = str(uuid4())
    conversation_id = f"attack-chain-custom-{execution_id}"
    tool_call = {"tool": normalized["tool"], "arguments": deepcopy(normalized["arguments"])}
    sandbox = _comparison_sandbox(execution_id, "with-guard" if guard_enabled else "without-guard")
    init_sandbox(sandbox)
    initial = _environment_snapshot(sandbox)
    stage_results: list[dict[str, Any]] = []
    executor_stage: dict[str, Any] | None = None
    planner_seed = _seal_chain_artifact(
        "chain-input",
        "request-envelope",
        [],
        {
            "payload_hash": _stable_hash(normalized["payload"]),
            "tool_call": deepcopy(tool_call),
            "tool_call_hash": tool_call_hash(tool_call),
            "agent_id": normalized["agent_id"],
            "agent_role": normalized["agent_role"],
            "context_sources": deepcopy(normalized["context_sources"]),
        },
    )
    prior_artifact: dict[str, Any] = planner_seed

    for stage_id, stage_name, stage_role, executes in CUSTOM_CHAIN_STAGES:
        stage_agent_id = f"{normalized['agent_id']}::{stage_id}"
        stage_before = _environment_snapshot(sandbox)
        stage_tool_call = deepcopy(
            stage_results[0]["artifact"]["data"]["planned_tool_call"]
            if stage_id == "executor"
            else tool_call
        )
        evaluation = evaluate_agent_event(
            {
                "conversation_id": conversation_id,
                "agent_id": stage_agent_id,
                "agent_role": stage_role,
                "source_app": "智安哨多 Agent 攻击链入口",
                "model_input": normalized["payload"],
                "model_output": normalized["payload"],
                "context_sources": normalized["context_sources"],
                "tool_call": stage_tool_call,
                "execute_in_sandbox": executes,
                "stage_context": {"source": prior_artifact["producer_stage"], "artifact": prior_artifact},
            },
            guard_enabled=guard_enabled,
            execute_in_sandbox=executes,
            review_scope="experiment",
            sandbox=sandbox,
        )
        after = _environment_snapshot(sandbox)
        receipt = _record_server_execution_receipt(evaluation, stage_tool_call, stage_agent_id)
        branch = _environment_branch(stage_before, after, evaluation)
        if stage_id == "planner":
            artifact_type = "execution-plan"
            artifact_inputs = [planner_seed["artifact_hash"]]
            artifact_data = {
                "origin": "caller-authored-request",
                "payload_hash": planner_seed["data"]["payload_hash"],
                "planned_tool_call": deepcopy(tool_call),
            "planned_tool_call_hash": tool_call_hash(tool_call),
                "execution_constraints": {"target": "sandbox", "max_attempts": 1},
            }
        elif stage_id == "executor":
            artifact_type = "execution-evidence"
            artifact_inputs = [prior_artifact["artifact_hash"]]
            artifact_data = {
                "consumed_plan_hash": prior_artifact["artifact_hash"],
                "planned_tool_call_hash": prior_artifact["data"]["planned_tool_call_hash"],
                "actual_tool_call_hash": tool_call_hash(stage_tool_call),
                "audit_id": evaluation.get("audit_id", ""),
                "audit_hash": (evaluation.get("audit_log") or {}).get("audit_hash", ""),
                "receipt_hash": receipt.get("receipt_hash", ""),
                "receipt_status": receipt.get("status", ""),
                "result_hash": receipt.get("result_hash", ""),
                "before_state_hash": branch["before"]["state_hash"],
                "after_state_hash": branch["after"]["state_hash"],
                "effect_observed": bool(branch.get("effect_observed")),
                "attack_success": bool(branch.get("attack_success")),
            }
        elif stage_id == "behavior-supervisor":
            artifact_type = "supervisor-verdict"
            artifact_inputs = [prior_artifact["artifact_hash"]]
            executor_data = prior_artifact["data"]
            receipt_consistent = bool(executor_data.get("receipt_hash")) and (
                executor_data.get("receipt_status") != "completed"
                or bool(executor_data.get("result_hash"))
            )
            artifact_data = {
                "consumed_execution_hash": prior_artifact["artifact_hash"],
                "decision": executor_stage["evaluation"].get("decision", "") if executor_stage else "",
                "policy_id": executor_stage["evaluation"].get("policy_id", "") if executor_stage else "",
                "receipt_consistent": receipt_consistent,
                "effect_observed": bool(executor_data.get("effect_observed")),
                "controlled": bool(
                    executor_stage
                    and executor_stage["evaluation"].get("decision") in CONTROL_DECISIONS
                    and not executor_data.get("attack_success")
                ),
                "evidence_complete": bool(executor_data.get("audit_hash")) and receipt_consistent,
            }
        else:
            artifact_type = "evaluation-summary"
            artifact_inputs = [item["artifact"]["artifact_hash"] for item in stage_results]
            execution_data = stage_results[1]["artifact"]["data"]
            verdict_data = stage_results[2]["artifact"]["data"]
            artifact_data = {
                "consumed_artifact_hashes": artifact_inputs,
                "evaluation_source": "deterministic-evidence-aggregation",
                "attack_success": bool(execution_data.get("attack_success")),
                "side_effect_observed": bool(execution_data.get("effect_observed")),
                "controlled": bool(verdict_data.get("controlled")),
                "execution_status": execution_data.get("receipt_status", ""),
                "evidence_complete": bool(verdict_data.get("evidence_complete")),
            }
        stage_artifact = _seal_chain_artifact(stage_id, artifact_type, artifact_inputs, artifact_data)
        stage_result = {
            "stage_id": stage_id,
            "stage_name": stage_name,
            "stage_role": stage_role,
            "agent_id": stage_agent_id,
            "conversation_id": conversation_id,
            "payload": normalized["payload"],
            "tool_call": stage_tool_call,
            "execution_attempted": executes,
            "stage_context": {"source": prior_artifact["producer_stage"], "artifact": deepcopy(prior_artifact)},
            "artifact": stage_artifact,
            "evaluation": evaluation,
            "audit": {
                "audit_id": evaluation.get("audit_id", ""),
                "audit_hash": (evaluation.get("audit_log") or {}).get("audit_hash", ""),
            },
            "receipt": receipt,
            "environment": branch,
        }
        stage_results.append(stage_result)
        prior_artifact = stage_artifact
        if executes:
            executor_stage = stage_result

    if executor_stage is None:  # Defensive: CUSTOM_CHAIN_STAGES always includes executor.
        raise RuntimeError("攻击链缺少执行阶段")

    chain = [
        {
            "agent": stage["stage_name"],
            "status": (
                "completed"
                if stage["evaluation"].get("decision") == "允许"
                else stage["evaluation"].get("decision", "not_executed")
            ),
            "evidence": (
                f"evaluation={stage['evaluation'].get('audit_id', '')}; "
                f"audit={stage['audit'].get('audit_hash', '')}; "
                f"receipt={stage['receipt'].get('receipt_hash', '')}"
            ),
        }
        for stage in stage_results
    ]
    executor_evaluation = executor_stage["evaluation"]
    executor_receipt = executor_stage["receipt"]
    executor_environment = executor_stage["environment"]
    final_data = stage_results[3]["artifact"]["data"]
    final_outcome = (
        "controlled"
        if final_data.get("controlled")
        else "attack_success"
        if final_data.get("attack_success")
        else "side_effect_only"
        if final_data.get("side_effect_observed")
        else "not_executed"
    )
    return {
        # Compatibility fields retain the former single-stage response shape;
        # they refer to the actual executor stage.
        "execution_id": execution_id,
        "conversation_id": conversation_id,
        "request": normalized,
        "tool_call": tool_call,
        "guard_enabled": guard_enabled,
        "evaluation": executor_evaluation,
        "environment": executor_environment,
        "audit": executor_stage["audit"],
        "receipt": executor_receipt,
        "summary": {
            "attack_success": bool(executor_evaluation.get("attack_success")),
            "controlled": executor_evaluation.get("decision") in CONTROL_DECISIONS
            and not executor_evaluation.get("attack_success"),
            "decision": executor_evaluation.get("decision", ""),
            "policy_id": executor_evaluation.get("policy_id", ""),
            "execution_status": executor_receipt.get("status", ""),
            "stage_count": len(stage_results),
            "all_stages_audited": all(stage["audit"]["audit_hash"] for stage in stage_results),
            "all_stages_receipted": all(stage["receipt"].get("receipt_hash") for stage in stage_results),
            "shared_conversation_id": conversation_id,
            "final_outcome": final_outcome,
            "evidence_complete": bool(final_data.get("evidence_complete")),
        },
        "chain": chain,
        "stages": stage_results,
        "stage_evaluations": [stage["evaluation"] for stage in stage_results],
        "stage_receipts": [stage["receipt"] for stage in stage_results],
        "artifacts": [stage["artifact"] for stage in stage_results],
        "final_evaluation": stage_results[3]["artifact"],
        "chain_integrity": {
            "same_payload": all(stage["payload"] == normalized["payload"] for stage in stage_results),
            "same_tool_call": all(stage["tool_call"] == tool_call for stage in stage_results),
            "shared_conversation_id": all(stage["conversation_id"] == conversation_id for stage in stage_results),
            "initial_state_hash": initial["state_hash"],
            "final_state_hash": _environment_snapshot(sandbox)["state_hash"],
            "planner_tool_call_hash": stage_results[0]["artifact"]["data"]["planned_tool_call_hash"],
            "executor_tool_call_hash": tool_call_hash(executor_stage["tool_call"]),
            "artifact_hashes_valid": all(_verify_chain_artifact(stage["artifact"]) for stage in stage_results),
            "executor_consumed_planner_artifact": executor_stage["artifact"]["input_artifact_hashes"]
            == [stage_results[0]["artifact"]["artifact_hash"]]
            and executor_stage["artifact"]["data"]["actual_tool_call_hash"]
            == stage_results[0]["artifact"]["data"]["planned_tool_call_hash"],
            "supervisor_consumed_execution_artifact": stage_results[2]["artifact"]["input_artifact_hashes"]
            == [stage_results[1]["artifact"]["artifact_hash"]],
            "evaluator_consumed_prior_artifacts": stage_results[3]["artifact"]["input_artifact_hashes"]
            == [stage["artifact"]["artifact_hash"] for stage in stage_results[:3]],
            "artifact_chain_valid": _verify_chain_artifacts(stage_results),
            "chain_root_hash": stage_results[3]["artifact"]["artifact_hash"],
        },
    }


def _seal_chain_artifact(
    producer_stage: str,
    artifact_type: str,
    input_artifact_hashes: list[str],
    data: dict[str, Any],
) -> dict[str, Any]:
    artifact = {
        "schema_version": "agent-supervisor.custom-chain-artifact.v1",
        "artifact_type": artifact_type,
        "producer_stage": producer_stage,
        "input_artifact_hashes": deepcopy(input_artifact_hashes),
        "data": deepcopy(data),
    }
    artifact["artifact_hash"] = _stable_hash(artifact)
    return artifact


def _verify_chain_artifact(artifact: dict[str, Any]) -> bool:
    expected = str(artifact.get("artifact_hash", ""))
    unsigned = {key: value for key, value in artifact.items() if key != "artifact_hash"}
    return bool(expected) and expected == _stable_hash(unsigned)


def _verify_chain_artifacts(stage_results: list[dict[str, Any]]) -> bool:
    if len(stage_results) != 4 or not all(_verify_chain_artifact(stage["artifact"]) for stage in stage_results):
        return False
    artifacts = [stage["artifact"] for stage in stage_results]
    return (
        artifacts[1]["input_artifact_hashes"] == [artifacts[0]["artifact_hash"]]
        and artifacts[2]["input_artifact_hashes"] == [artifacts[1]["artifact_hash"]]
        and artifacts[3]["input_artifact_hashes"] == [artifact["artifact_hash"] for artifact in artifacts[:3]]
        and artifacts[1]["data"].get("consumed_plan_hash") == artifacts[0]["artifact_hash"]
        and artifacts[2]["data"].get("consumed_execution_hash") == artifacts[1]["artifact_hash"]
    )


def _record_server_execution_receipt(result: dict[str, Any], tool_call: dict[str, Any], agent_id: str) -> dict[str, Any]:
    """Persist a signed receipt for the sandbox execution that just finished."""
    audit_log = result.get("audit_log") or {}
    tool_output = audit_log.get("tool_output") or {}
    executed = bool(tool_output.get("executed"))
    timed_out = bool(tool_output.get("timed_out"))
    exit_code = tool_output.get("exit_code")
    failed = executed and (timed_out or (exit_code is not None and exit_code != 0))
    status = "failed" if failed else "completed" if executed else "not_executed"
    error = ""
    if failed:
        error = str(tool_output.get("output") or "工具执行失败")[:2000]
    elif not executed:
        error = str(tool_output.get("output", ""))[:2000]
    duration_ms = result.get("execution_duration_ms")
    if duration_ms is None:
        duration_ms = tool_output.get("duration_ms", 0)
    try:
        duration_ms = round(max(0.0, float(duration_ms)), 3)
    except (TypeError, ValueError):
        duration_ms = 0
    receipt = complete_execution(
        str(result.get("audit_id", "")),
        {
            "receipt_id": f"custom-{result.get('run_id', '')}",
            "agent_id": agent_id,
            "tool_call": tool_call,
            "status": status,
            "execution_target": "sandbox" if executed else "none",
            "result_hash": str(result.get("execution_result_hash") or _stable_hash(tool_output)) if executed else "",
            "duration_ms": duration_ms,
            "error": error,
        },
    )
    return receipt.get("receipt") or {}


